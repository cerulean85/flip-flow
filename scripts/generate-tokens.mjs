import { readFileSync, writeFileSync } from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, "..")
const tokens = JSON.parse(readFileSync(path.join(root, "design-tokens.json"), "utf8"))
const { light, dark, category, web } = tokens.color

const header = "Generated by scripts/generate-tokens.mjs from design-tokens.json. Do not edit by hand."

// Web: CSS variables per theme + Tailwind v4 theme mapping (surface -> bg-surface).
// Radius stays out of @theme: --radius-sm/md/lg would override Tailwind's rounded-* scale.
const twColor = (name) => (name === "white" || name === "black" ? name : `var(--color-${name})`)

// Web value: the Tailwind palette color from `web` when mapped, else the shared hex
const webColors = (colors, mode) => ({
  ...colors,
  ...Object.fromEntries(Object.entries(web).map(([name, pair]) => [name, twColor(pair[mode])])),
})

const cssVars = (colors) =>
  Object.entries(colors).map(([name, value]) => `  --${name}: ${value};`).join("\n")

const webLight = webColors(light, 0)
const webDark = webColors(dark, 1)

const css = `/* ${header} */

@theme inline {
${Object.keys(webLight).filter((name) => name !== "shadow").map((name) => `  --color-${name}: var(--${name});`).join("\n")}
${category.map((_, i) => `  --color-category-${i + 1}: var(--category-${i + 1});`).join("\n")}
}

:root {
${cssVars(webLight)}
${category.map((value, i) => `  --category-${i + 1}: ${value};`).join("\n")}
}

.dark {
${cssVars(webDark)}
}
`

// Mobile: keeps the existing ThemeColors keys so screens don't change
const mobileKeys = {
  bg: "bg",
  card: "surface",
  cardAlt: "surface-muted",
  border: "border",
  text: "text",
  textMuted: "text-muted",
  textSubtle: "text-subtle",
  primary: "primary",
  primaryFg: "primary-fg",
  primarySoft: "primary-soft",
  primarySoftText: "primary-soft-text",
  accent: "accent",
  danger: "danger",
  dangerFg: "danger-fg",
  shadow: "shadow",
  star: "star",
}

const tsColors = (colors) =>
  Object.entries(mobileKeys).map(([key, name]) => `  ${key}: ${JSON.stringify(colors[name])},`).join("\n")

const ts = `// ${header}

export const lightColors = {
${tsColors(light)}
} as const

export const darkColors = {
${tsColors(dark)}
} as const

export const CATEGORY_COLORS = ${JSON.stringify(category)} as const

export const RADIUS = ${JSON.stringify(tokens.radius)} as const

export const SPACE = ${JSON.stringify(tokens.space)} as const
`

writeFileSync(path.join(root, "src/app/tokens.css"), css)
writeFileSync(path.join(root, "mobile/lib/tokens.generated.ts"), ts)
console.log("✓ tokens: src/app/tokens.css, mobile/lib/tokens.generated.ts")
